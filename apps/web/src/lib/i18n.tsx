const dictionaries: Record<Locale, DeepPartial<Dict>> = { en, ms, zh, ta: {} };

export const LOCALE_LABELS: Array<{ code: Locale; label: string }> = [
  { code: 'ms', label: 'BM' },
  { code: 'en', label: 'EN' },
  { code: 'zh', label: '中文' },
];

function lookup(dict: any, path: string): string | undefined {
  return path.split('.').reduce((o, k) => (o == null ? undefined : o[k]), dict);
}

type Ctx = {
  locale: Locale;
  setLocale: (l: Locale) => void;
  t: (key: string, vars?: Record<string, string | number>) => string;
  /** Pick the right language from an i18n object from the API (e.g. machine instructions). */
  tx: (text: Partial<Record<Locale, string>> | null | undefined) => string;
};

const I18nContext = createContext<Ctx | null>(null);
const STORAGE_KEY = 'dobi.locale';

function initialLocale(): Locale {
  try {
    const saved = localStorage.getItem(STORAGE_KEY) as Locale | null;
    if (saved && saved in dictionaries) return saved;
  } catch {
    /* ignore */
  }
  const nav = navigator.language.toLowerCase();
  if (nav.startsWith('ms') || nav.startsWith('id')) return 'ms';
  if (nav.startsWith('zh')) return 'zh';
  return 'en';
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>(initialLocale);
  useEffect(() => {
    document.documentElement.lang = locale === 'zh' ? 'zh-Hans' : locale;
  }, [locale]);
  const setLocale = useCallback((l: Locale) => {
    setLocaleState(l);
    try {
      localStorage.setItem(STORAGE_KEY, l);
    } catch {
      /* ignore */
    }
  }, []);
  const value = useMemo<Ctx>(
    () => ({
      locale,
      setLocale,
      t: (key, vars) => {
        const raw = lookup(dictionaries[locale], key) ?? lookup(en, key) ?? key;
        return vars ? raw.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? '')) : raw;
      },
      tx: (text) => pickText(text, locale),
    }),
    [locale, setLocale],
  );
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error('useI18n outside provider');
  return ctx;
}
